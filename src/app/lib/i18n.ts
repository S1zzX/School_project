const translations: Record<string, typeof en> = { en, vi };

/** Hook — returns a translator function bound to the current language */
export function useT() {
  const { language } = useAppSettings();
  const dict = translations[language] ?? en;
  return (key: TranslationKey, fallback?: string): string =>
    dict[key] ?? en[key] ?? fallback ?? key;
}
